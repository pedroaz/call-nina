import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const renderer = fileURLToPath(new URL("../src/renderer/", import.meta.url));
const modules = new Map();
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) await collect(filename);
    else if (entry.name.endsWith(".module.css")) {
      if (modules.has(entry.name)) throw new Error("OD_CSS_MODULE_NAME_CONFLICT");
      const css = (await readFile(filename, "utf8")).replace(/\/\*[\s\S]*?\*\//gu, "");
      const classes = [
        ...new Set([...css.matchAll(/\.([A-Za-z_][\w-]*)/gu)].map((match) => match[1])),
      ].sort();
      modules.set(entry.name, classes);
    }
  }
}
await collect(renderer);
const content =
  "// Generated by scripts/generate-css-types.mjs from renderer CSS modules.\n" +
  [...modules]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([name, classes]) =>
        `declare module "*${name}" {\n  const styles: {\n${classes.map((name) => `    readonly ${/^[A-Za-z_$][\w$]*$/u.test(name) ? name : JSON.stringify(name)}: string;`).join("\n")}\n  };\n  export default styles;\n}\n`,
    )
    .join("\n");
const target = path.join(renderer, "styles/css-modules.d.ts");
if ((await readFile(target, "utf8").catch(() => "")) !== content) await writeFile(target, content);
