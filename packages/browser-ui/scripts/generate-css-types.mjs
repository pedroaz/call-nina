import { readdir, readFile, writeFile } from "node:fs/promises";

const source = new URL("../src/", import.meta.url);
const declarations = [];
for (const name of (await readdir(source)).filter((name) => name.endsWith(".module.css")).sort()) {
  const css = (await readFile(new URL(name, source), "utf8")).replace(/\/\*[\s\S]*?\*\//gu, "");
  const classes = [
    ...new Set([...css.matchAll(/\.([A-Za-z_][\w-]*)/gu)].map((match) => match[1])),
  ].sort();
  declarations.push(
    `declare module "*${name}" {\n  const styles: {\n${classes.map((className) => `    readonly ${className}: string;`).join("\n")}\n  };\n  export default styles;\n}`,
  );
}
const content = `// Generated by scripts/generate-css-types.mjs.\n${declarations.join("\n\n")}\n`;
const target = new URL("../src/css-modules.d.ts", import.meta.url);
if ((await readFile(target, "utf8").catch(() => "")) !== content) {
  await writeFile(target, content);
}
